// Dev tool: builds app/js/content/zh/strokes.js (stroke order for the Chinese course's characters)
// from Make Me a Hanzi's graphics.txt: each stroke's centre line ("median"), turned into a path on
// the same 109×109 grid as the Japanese KanjiVG strokes so the tracing code works unchanged.
// Usage: node scripts/strokes-zh.mjs /path/to/makemeahanzi
// Make Me a Hanzi graphics data (derived from Arphic fonts), Arphic Public License.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the makemeahanzi checkout folder');
globalThis.__HAJIME_COURSE__ = 'zh';
const { KANJI } = await import('../app/js/content/zh/hanzi.js');
const { PEEK_KANJI } = await import('../app/js/content/zh/index.js');

const wanted = new Set([...KANJI.map((k) => k.k), ...PEEK_KANJI.map((k) => k.k)]);
const S = 109 / 1024;
const pt = ([x, y]) => `${(x * S).toFixed(1)},${((900 - y) * S).toFixed(1)}`;
const out = {};
for (const line of readFileSync(join(dir, 'graphics.txt'), 'utf8').split('\n')) {
  if (!line) continue;
  const { character, medians } = JSON.parse(line);
  if (!wanted.has(character)) continue;
  out[character] = medians.map((m) => `M${pt(m[0])}${m.slice(1).map((p) => `L${pt(p)}`).join('')}`);
}
const missing = [...wanted].filter((c) => !out[c]);
const header = `// Stroke-order paths (109×109 grid) for the Chinese course, generated by scripts/strokes-zh.mjs — do
// not edit by hand. Data from Make Me a Hanzi (https://github.com/skishore/makemeahanzi), derived
// from Arphic fonts, Arphic Public License.
`;
writeFileSync(new URL('../app/js/content/zh/strokes.js', import.meta.url), `${header}export const STROKES = ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} characters written; missing: ${missing.join(' ') || 'none'}`);
