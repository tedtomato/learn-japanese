// Dev tool: builds app/js/content/strokes.js (stroke-order paths) from a KanjiVG checkout.
// Usage: node scripts/strokes.mjs /path/to/kanjivg
// KanjiVG © Ulrich Apel, CC BY-SA 3.0 — https://kanjivg.tagaini.net
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { HIRAGANA_ROWS, KATAKANA_ROWS } from '../app/js/content/kana.js';
import { KANJI, RADICALS } from '../app/js/content/kanji.js';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the KanjiVG checkout folder');

const chars = new Set(['っ', 'ゃ', 'ゅ', 'ょ', 'ッ', 'ャ', 'ュ', 'ョ', 'ー']);
for (const rows of [HIRAGANA_ROWS, KATAKANA_ROWS]) for (const row of rows) for (const [k] of row.kana) chars.add(k);
for (const k of KANJI) chars.add(k.k);
for (const r of RADICALS) chars.add(r.r);

export const missing = [];
const out = {};
for (const ch of chars) {
  const file = join(dir, 'kanji', `${ch.codePointAt(0).toString(16).padStart(5, '0')}.svg`);
  if (!existsSync(file)) {
    missing.push(ch);
    continue;
  }
  const svg = readFileSync(file, 'utf8');
  out[ch] = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1].replace(/(\d)\.(\d)\d+/g, '$1.$2'));
}

const header = `// Stroke-order paths (109×109 grid), generated by scripts/strokes.mjs — do not edit by hand.
// Data from KanjiVG © Ulrich Apel, licensed CC BY-SA 3.0 (https://kanjivg.tagaini.net).
`;
writeFileSync(new URL('../app/js/content/strokes.js', import.meta.url), `${header}export const STROKES = ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} characters written; missing: ${missing.join(' ') || 'none'}`);
